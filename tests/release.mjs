import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile, cp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
const source = path.resolve(import.meta.dirname, "../dist");
const host = path.resolve(process.env.GENEX_HOST_DIR || path.resolve(import.meta.dirname, "../../genex-plugin-0.1.12"));
const { PluginRegistry } = await import(pathToFileURL(path.join(host, "src/substrate/plugins/registry.ts")).href);
const { EventStore } = await import(pathToFileURL(path.join(host, "src/substrate/event-store.ts")).href);
const root = await mkdtemp(path.join(os.tmpdir(), "usage-streak-release-"));
const profile = path.join(root, "Genex"), plugins = path.join(profile, "engine-homes/plugins"), seeds = path.join(root, "seeds");
await mkdir(path.join(profile, "exoharness/agents/studio/conversations"), { recursive: true });
await mkdir(seeds, { recursive: true });
await writeFile(path.join(profile, "projects.json"), JSON.stringify({ recents: [] }));
const manifest = JSON.parse(await readFile(path.join(source, "plugin.json"), "utf8"));
const registry = new PluginRegistry(plugins, seeds, path.join(host, "src/plugin-sdk/backend.mjs"), async (id, method) => {
  assert.equal(id, manifest.id);
  assert.equal(method, "storage.root");
  return path.join(plugins, "data", id);
});
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
const binding = { project: "fixture", directory: path.join(root, "game"), threadId: "same-existing-chat" };
await mkdir(binding.directory);
// Write disposable history with the released application's own writer, not a guessed disk format.
const store = await EventStore.open(path.join(profile, "exoharness"));
await store.createThread({ threadId: binding.threadId, metadata: { project: binding.project } });
await store.appendEvents(binding.threadId, [{ type: "messages", messages: [{ role: "assistant", content: "private fixture content" }], usage: { input_tokens: 10, output_tokens: 5 } }]);
const beforeRecord = await readFile(store.recordPath(binding.threadId), "utf8");
registry.consent = async () => ({ approved: true, by: "user" });
const tool = manifest.id + "__usage-summary";
try {
  await registry.init();
  await registry.installLocal(source, "local", manifest.capabilities, source);
  check("fresh install is accepted by stock Genex and stays disabled", registry.list().find(p => p.manifest.id === manifest.id)?.enabled === false);
  await assert.rejects(registry.tool(tool, { zone: "UTC" }, binding));
  checks.push("disabled plugin cannot run its chat tool");
  await registry.setEnabled(manifest.id, true);
  const result = await registry.tool(tool, { zone: "UTC" }, binding);
  const summary = JSON.parse(result.text);
  check("real harmless chat-tool backend call succeeds after enabling in the same chat", summary.reportedTokens === 15 && summary.scope.includes("not billing"));
  check("stock event-store history is read without returning private message contents", !result.text.includes("private fixture content"));
  check("new id detects the profile with no manual override", (await registry.settings(manifest.id)).profile === "");
  await registry.setSetting(manifest.id, "profile", profile);
  const answer = await registry.action(manifest.id, "analytics", { zone: "UTC" });
  check("real panel action works on stock Genex", answer.callCount === 1 && answer.projects.length === 1);
  check("reading usage preserves the committed conversation record", await readFile(store.recordPath(binding.threadId), "utf8") === beforeRecord);
  const update = path.join(root, "update");
  await cp(source, update, { recursive: true });
  const next = { ...manifest, version: "1.1.2" };
  await writeFile(path.join(update, "plugin.json"), JSON.stringify(next, null, 2));
  await registry.installLocal(update, "local", manifest.capabilities, source);
  check("settings survive a same-identity update", (await registry.settings(manifest.id)).profile === profile);
  await registry.setEnabled(manifest.id, false);
  await assert.rejects(registry.action(manifest.id, "analytics", { zone: "UTC" }));
  await assert.rejects(registry.tool(tool, {}, binding));
  checks.push("disable refuses both panel actions and tools");
  await registry.setEnabled(manifest.id, true);
  check("re-enable does not need a new chat", JSON.parse((await registry.tool(tool, { zone: "UTC" }, binding)).text).reportedTokens === 15);
  await registry.remove(manifest.id);
  check("remove marks the plugin removed", registry.list().find(p => p.manifest.id === manifest.id)?.removed === true);
  await assert.rejects(registry.tool(tool, {}, binding));
  await assert.rejects(registry.action(manifest.id, "analytics", { zone: "UTC" }));
  checks.push("removed plugin cannot run actions or tools");
  const report = { checks, host: "unmodified Genex v0.1.12", providers: "synthetic chat binding, no model calls or accounts" };
  await mkdir(path.resolve(import.meta.dirname, "../.evidence"), { recursive: true });
  await writeFile(path.resolve(import.meta.dirname, "../.evidence/release.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  registry.cancel();
  assert.ok(path.resolve(root).startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(root).startsWith("usage-streak-release-"));
  await rm(root, { recursive: true, force: true, maxRetries: 8, retryDelay: 100 });
}
